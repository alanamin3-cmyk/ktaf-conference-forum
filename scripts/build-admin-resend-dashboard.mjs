// Produce one self-contained file for Supabase's dashboard editor.
// The public registration template is copied verbatim from the shared source.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {dirname,resolve} from 'node:path';
import ts from 'typescript';
const sources = [
  'supabase/functions/_shared/ktaf-registration-email.ts',
  'supabase/functions/_shared/send-registration-confirmation.ts',
  'supabase/functions/resend-registration/handler.mjs',
  'supabase/functions/resend-registration/index.ts',
];
let combined='// Generated by scripts/build-admin-resend-dashboard.mjs. Edit the source files.\n';
for(const path of sources){
  const source=(await readFile(path,'utf8')).replace(/^import .+ from ["']\..+["'];\r?\n/gm,'');
  combined+='\n// '+path+'\n'+ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
}
const output=resolve(process.argv[2] || '../admin-portal-update-2026-09-21/resend-registration-dashboard.txt');
await mkdir(dirname(output),{recursive:true});
await writeFile(output,combined);
console.log(output);
